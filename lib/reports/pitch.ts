// 상품 상세 화면이 쓰는 판매 문구.
//
// 카탈로그(catalog.ts)는 무엇을 파는지를 적는 곳이고, 여기는 어떻게 말하는지를 적는 곳이다.
// 나눠 둔 이유는 하나다 — 문구는 자주 고치게 되고, 고칠 때마다 가격·목차·질문이 들어 있는
// 파일을 건드리고 싶지 않다.
//
// 세 단언(claims)은 상세 화면 맨 위에 큰 글씨로 깔린다. 두루뭉술하면 아무 힘이 없다.
// "좋은 인연이 올 거예요" 말고 "언제 열리는지 달로 짚어 드려요" 처럼, 이 풀이가 실제로
// 내놓는 것을 그대로 적는다. 본문이 못 하는 약속은 적지 않는다 — 제목이 약속한 걸 본문이
// 안 지키면 그게 환불 사유가 된다.

