/**
 * 바꾼 말 뒤의 조사를 고친다.
 *
 * "명식을" 을 그대로 바꾸면 "여덟 글자을" 이 된다. 받침이 달라졌으니 조사도 달라져야
 * 한다. 글 전체의 조사를 손보지는 않는다 — "사과 한 개" 의 「과」까지 조사로 보고
 * 고치면 "사와 한 개" 가 된다. 우리가 방금 바꾼 자리의 바로 뒤만 본다.
 */
const JOSA_PAIRS: Array<[string, string]> = [
  ["이에요", "예요"],
  ["이라", "라"],
  ["으로", "로"],
  ["을", "를"],
  ["이", "가"],
  ["은", "는"],
  ["과", "와"],
];

function fixTail(word: string, tail: string) {
  const pair = JOSA_PAIRS.find(([withBatchim, without]) => tail === withBatchim || tail === without);
  if (!pair) return `${word}${tail}`;
  return `${word}${hasBatchim(word) ? pair[0] : pair[1]}`;
}

/** 조사까지 함께 보고 바꾼다 */
function swap(text: string, pattern: RegExp, replacement: string) {
  // 긴 짝부터 봐야 "이에요" 가 "이" 로 잘리지 않는다
  const withTail = new RegExp(`(?:${pattern.source})(이에요|예요|이라|으로|을|를|이|가|은|는|과|와|라|로)?`, pattern.flags);
  return text.replace(withTail, (matched, ...rest) => {
    const tail = rest.find((value) => typeof value === "string" && JOSA_TAILS.has(value)) as string | undefined;
    const groups = rest.slice(0, -2) as Array<string | undefined>;
    const body = replacement.replace(/\$(\d)/g, (_, index: string) => groups[Number(index) - 1] ?? "");
    // 조사 자리가 아니었으면(= 본문이 그 글자로 끝났으면) 손대지 않는다
    if (!tail || !matched.endsWith(tail)) return body;
    // 아예 지우는 규칙이면 뒤따르던 글자는 조사가 아니라 다음 문장의 첫 글자다.
    // "명리에서는 이 자리를" 에서 「이」까지 조사로 보고 고치면 "가 자리를" 이 된다.
    if (body === "") return tail;
    return fixTail(body, tail);
  });
}

const JOSA_TAILS = new Set(JOSA_PAIRS.flat());

/** 한 문장에서 용어와 뜻 없는 비유를 손님의 말로 바꾼다 */
export function plain(text: string) {
  const swapped = [...PLAIN_EMPTY, ...PLAIN].reduce(
    (current, [pattern, replacement]) => swap(current, pattern, replacement),
    text,
  );
  // 한자를 들어내면 「 」 안이 비거나 가운뎃점이 외톨이로 남는다
  return swapped
    .replace(/「\s*」/g, "")
    .replace(/\s*·\s*(?=[.,」)]|$)/g, "")
    .replace(/\(\s*\)/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}

/** 객체·배열 안의 모든 문자열을 손님의 말로 바꾼다 */
export function plainDeep<T>(value: T): T {
  if (typeof value === "string") return plain(value) as T;
  if (Array.isArray(value)) return value.map((item) => plainDeep(item)) as T;
  if (value && typeof value === "object") {
    const result: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value)) result[key] = plainDeep(item);
    return result as T;
  }
  return value;
}

/** 손님 글에 샌 용어를 모아 돌려준다 (없으면 빈 배열) */
export function findJargon(text: string): string[] {
  const hanja = /[\u4e00-\u9fff]/.test(text) ? ["한자"] : [];
  // "메시지" 안의 "시지" 처럼, 보통 말 속에 우연히 들어 있는 글자는 용어가 아니다
  const FALSE_FRIENDS: Record<string, RegExp> = {
    시지: /(?<!메)시지/,
    관대: /(?<!너)관대(?!하)/,
    중화: /중화(?!요리)/,
  };
  const ganji = GANJI_SHAPES.some((shape) => shape.test(text)) ? ["간지"] : [];
  return [
    ...JARGON.filter((word) => (FALSE_FRIENDS[word] ? FALSE_FRIENDS[word]!.test(text) : text.includes(word))),
    ...ganji,
    ...hanja,
  ];
}

/**
 * 뜻 없는 비유.
 *
 * 용어를 막아 두니 그 자리를 이런 말이 메우기 시작했다. "해와 달이 부딪히는 자리",
 * "뜨거운 달에 태어난 물", "네 기둥이 말하기를". 용어보다 나쁘다 — 용어는 찾아보면
 * 뜻이라도 나오는데, 이건 찾아봐도 아무 뜻이 없다. 읽는 사람은 용어를 몰라서 못
 * 읽는 게 아니라 무슨 얘긴지 몰라서 못 읽는다.
 *
 * 글자 수만 차지하고 값을 깎는 말이라, 샜으면 용어와 똑같이 남긴다.
 */
const EMPTY_TALK = [
  "해와 달", "해와 시", "달과 시", "날과 시", "해와 날",
  "뜨거운 달", "차가운 달", "뜨거운 해", "차가운 물", "큰 나무", "단단한 쇠",
  "네 기둥", "기둥이", "기둥은", "자리의 뜻",
];

/** 손님 글에 샌 뜻 없는 비유를 모아 돌려준다 */
export function findEmptyTalk(text: string): string[] {
  return EMPTY_TALK.filter((phrase) => text.includes(phrase));
}

/**
 * 시기 칸에 붙는 간지 꼬리를 뗀다.
 *
 * "36~45세 · 경신 대운", "2027 정미 세운" 처럼 우리끼리 쓰는 이름이 뒤에 붙어 나온다.
 * 모양이 늘 같아서 이것만은 기계로 떼도 문장이 망가지지 않는다. 손님에게 필요한 것은
 * 달력에서 찾을 수 있는 앞쪽뿐이다.
 */
function stripGanziTail(text: string) {
  return text
    .replace(/\s*·\s*[가-힣]{2}\s*(대운|세운|월운|일운)/g, "")
    .replace(/\s*[가-힣]{2}\s*(대운|세운|월운|일운)\s*/g, " ")
    .replace(/\s{2,}/g, " ")
    .trim();
}

/** 한 문장(또는 짧은 텍스트)에서 점수·위협 표현을 걷어낸다 */
export function soften(text: string) {
  const softened = SOFTEN.reduce((current, [pattern, replacement]) => current.replace(pattern, replacement), text);
  return stripGanziTail(softened).replace(/\s{2,}/g, " ").trim();
}

/**
 * 객체·배열 안의 모든 문자열에 soften 을 적용한다.
 * AI 가 만든 보고서 JSON 전체를 통과시키는 용도.
 */
export function softenDeep<T>(value: T): T {
  if (typeof value === "string") return soften(value) as T;
  // 아래 재귀가 끝나면 한 번에 살펴본다(문자열마다 로그를 찍으면 시끄럽다)
  if (Array.isArray(value)) return value.map((item) => softenDeep(item)) as T;
  if (value && typeof value === "object") {
    const result: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value)) result[key] = softenDeep(item);
    return result as T;
  }
  return value;
}

/**
 * 보고서 한 벌을 손님에게 내보내기 전에 살핀다.
 *
 * 막지는 않는다 — 용어가 하나 섞였다고 돈 낸 사람에게 아무것도 주지 않는 쪽이 더 나쁘다.
 * 대신 무엇이 샜는지 남긴다. 고쳐야 할 것은 프롬프트고, 고치려면 샜다는 걸 알아야 한다.
 */
export function auditReport(value: unknown, label: string): string[] {
  const text = JSON.stringify(value);
  const leaked = Array.from(new Set(findJargon(text)));
  if (leaked.length > 0) console.warn(`[풀이] 손님 글에 용어가 샜습니다 (${label}): ${leaked.join(", ")}`);

  const empty = Array.from(new Set(findEmptyTalk(text)));
  if (empty.length > 0) console.warn(`[풀이] 뜻 없는 비유가 샜습니다 (${label}): ${empty.join(", ")}`);

  return [...leaked, ...empty];
}
