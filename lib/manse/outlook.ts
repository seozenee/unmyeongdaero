/** 사건 예언 대신 계산된 시기별 주제·실천·주의를 빠짐없이 전달한다. */
export function buildActionableOutlook(pillars: FourPillars, life: LifeTimeline, isFemale: boolean): ActionableOutlook {
  const day = pillars.day.stem as Stem;
  const read = (ganji: string, period: string, age: number, year: number) => {
    const stem = ganji[0] as Stem; const branch = ganji[1] as Branch;
    const stemGod = tenGod(day, stem);
    const branchGod = branchTenGod(day, branch);
    const stage = twelveStage(day, branch);
    const relations = incomingRelations(pillars, { stem, branch, label: "시기" });
    const clash = relations.find(item => ["충", "형", "자형", "파", "해"].includes(item.type));
    // 부딪히는 자리를 찾으면 그 자리의 말로, 없으면 그 해 십성이 지나칠 때의 모습으로.
    const clashSeat = clash
      ? [clash.sourcePosition, clash.targetPosition].filter(position => !position.includes("시기"))
        .map(position => CAUTION_BY_SEAT[position.trim().charAt(0)]).find(Boolean)
      : undefined;
    const young = age < 20;
    const senior = age >= 70;
    return {
      period, age, year,
      basis: [`${ganji} · 천간 ${stemGod} · 지지 본기 ${branchGod} · 십이운성 ${stage}`, ...relations.slice(0, 3).map(item => `${item.type}: ${item.meaning}`)],
      money: young ? `${YOUNG_MONEY[stemGod]} ${YOUNG_CHECK}`
        : senior ? `${SENIOR_MONEY[stemGod]} ${SENIOR_CHECK}`
        : `${MONEY_MOVE[stemGod]} ${MONEY_CHECK[branchGod]}`,
      relationship: young ? `${YOUNG_LOVE[stemGod]} ${LOVE_CHECK[branchGod]}`
        : senior ? `${SENIOR_LOVE[stemGod]} ${LOVE_CHECK[branchGod]}`
        : `${LOVE_MOVE[stemGod]}${isFemale && stemGod === "정관" ? " 배우자를 보는 자리와도 겹칩니다." : !isFemale && stemGod === "정재" ? " 배우자를 보는 자리와도 겹칩니다." : ""} ${LOVE_CHECK[branchGod]}`,
      work: young ? `${YOUNG_WORK[stemGod]} ${WORK_CHECK[branchGod]}`
        : senior ? `${SENIOR_WORK[stemGod]} ${WORK_CHECK[branchGod]}`
        : `${WORK_MOVE[stemGod]} ${WORK_CHECK[branchGod]}`,
      do: DO_BY_STAGE[stage],
      caution: clashSeat ?? CAUTION_BY_GOD[stemGod],
    };
  };
  return {
    scope: "전통 명리에서 읽는 시기별 주제와 선택 기준입니다. 연도는 입춘 이후, 나이는 세는나이이며 수명이나 사건 발생을 뜻하지 않습니다.",
    pastAnnual: life.해마다[0] ? Array.from({ length:10 }, (_, i) => life.해마다[0]!.year - 10 + i)
      .filter(year => year >= life.해마다[0]!.year - life.나이 + 6)
      .map(year => { const birthYear = life.해마다[0]!.year - life.나이 + 1; return read(computeSeun(pillars, birthYear, year).ganji, `${year}년 · ${year - birthYear + 1}세`, year - birthYear + 1, year); }) : [],
    annual: life.해마다.slice(0, 10).map(y => read(y.ganji, `${y.year}년 · ${y.age}세`, y.age, y.year)),
    lifetime: life.열해.map(d => read(d.ganji, `${d.startAge}~${d.endAge}세 · ${d.startYear}~${d.endYear}년`, d.startAge, d.startYear)),
  };
}
